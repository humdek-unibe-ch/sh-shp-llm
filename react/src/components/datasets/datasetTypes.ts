/**
 * Dataset Type Definitions
 * ========================
 *
 * Types for the evaluation dataset system. Datasets are collections of
 * test cases used to evaluate prompt quality, run automated evaluations,
 * and provide examples for the Prompt Builder.
 *
 * Corresponds to `llm_eval_datasets` and `llm_eval_dataset_cases` DB tables.
 *
 * @module components/datasets/datasetTypes
 */

/** A dataset containing test cases for evaluation or prompt building. */
export interface PromptDataset {
  id: number;
  name: string;
  description?: string | null;
  dataset_type_code?: string | null;
  execution_profile_code?: string | null;
  cases_count?: number;
  owner_type_scope?: string | null;
  owner_id_scope?: number | null;
  is_locked?: number;
}

/** A single test case within a dataset, with input, expected output, and metadata. */
export interface PromptDatasetCase {
  id: number;
  id_llm_eval_datasets: number;
  link_id?: number | null;
  case_key: string;
  title?: string | null;
  case_type_code?: string | null;
  execution_profile_code?: string | null;
  source_type_code?: string | null;
  input_payload_json?: string;
  expected_output_json?: string | null;
  expected_labels_json?: string | null;
  source_ref_json?: string | null;
  provenance_json?: string | null;
  tags_json?: string | null;
  notes?: string | null;
  promoted_from_dataset_id?: number | null;
  promoted_by_run_case_id?: number | null;
  promotion_mode?: string | null;
  promoted_at?: string | null;
  evaluation_runs_count?: number;
  created_at?: string;
  updated_at?: string;
}

/** Expected classification labels for evaluation scoring (e.g., safety level). */
export interface PromptExpectedLabels {
  safety?: {
    danger_level?: null | 'warning' | 'critical' | 'emergency';
  };
}

/** Origin of an imported test case — determines which DB entity to reference. */
export type PromptImportSourceType =
  | 'playground_run'
  | 'form_submission'
  | 'conversation_message'
  | 'script_run';

/** A candidate record that can be imported as a dataset test case. */
export interface PromptImportCandidate {
  id: number;
  created_at?: string;
  updated_at?: string;
  id_llmConversations?: number | null;
  id_llm_scripts?: number | null;
  id_llmMessages_request?: number | null;
  id_llmMessages_response?: number | null;
  id_dataRows?: number | null;
  request_content?: string | null;
  response_content?: string | null;
  content?: string | null;
  role?: string | null;
  name?: string | null;
  model?: string | null;
  preview_text?: string | null;
  assistant_preview?: string | null;
}

/** Draft test case generated by the AI import mapper before user confirmation. */
export interface PromptAiImportCaseDraft {
  title: string;
  case_type?: string;
  source_type?: string;
  input_payload: Record<string, unknown>;
  expected_output?: Record<string, unknown> | null;
  expected_labels?: Record<string, unknown> | null;
  source_ref?: Record<string, unknown> | null;
  tags?: string[];
  notes?: string;
}

/** Response from the AI import parser containing mapped cases and metadata. */
export interface PromptAiImportParseResponse {
  mapping: Record<string, unknown>;
  cases: PromptAiImportCaseDraft[];
  warnings?: string[];
  model?: string | null;
  request_payload?: unknown;
  id_llmConversations?: number | null;
  id_llmMessages_request?: number | null;
  id_llmMessages_response?: number | null;
}
